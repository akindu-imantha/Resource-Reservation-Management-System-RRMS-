-- Initial RRMS schema, based on docs/rrms-erd.drawio.
-- This migration creates tables and constraints only; the ERD contains no seed records.

CREATE TABLE public.users (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'team_member'
    CHECK (role IN ('team_member', 'admin')),
  phone text,
  account_status text NOT NULL DEFAULT 'active'
    CHECK (account_status IN ('active', 'inactive', 'suspended')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_lower_unique ON public.users (lower(email));

CREATE TABLE public.admins (
  admin_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
  admin_level text NOT NULL DEFAULT 'admin',
  permissions jsonb NOT NULL DEFAULT '{}'::jsonb,
  appointed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.teams (
  team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_name text NOT NULL UNIQUE,
  description text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.team_members (
  member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  team_id bigint NOT NULL REFERENCES public.teams(team_id) ON DELETE CASCADE,
  joined_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT team_members_user_team_unique UNIQUE (user_id, team_id)
);

CREATE TABLE public.resource_categories (
  category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name text NOT NULL UNIQUE,
  description text
);

CREATE TABLE public.resources (
  resource_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id bigint REFERENCES public.resource_categories(category_id) ON DELETE SET NULL,
  name text NOT NULL,
  description text,
  capacity integer NOT NULL DEFAULT 1 CHECK (capacity > 0),
  location text,
  type text NOT NULL,
  availability_status text NOT NULL DEFAULT 'available'
    CHECK (availability_status IN ('available', 'unavailable', 'maintenance')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.reservations (
  reservation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id bigint NOT NULL REFERENCES public.resources(resource_id) ON DELETE RESTRICT,
  user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
  team_id bigint REFERENCES public.teams(team_id) ON DELETE SET NULL,
  start_time timestamptz NOT NULL,
  end_time timestamptz NOT NULL,
  purpose text NOT NULL,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled', 'completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reservations_time_range_valid CHECK (end_time > start_time)
);

CREATE INDEX team_members_team_id_idx ON public.team_members(team_id);
CREATE INDEX resources_category_id_idx ON public.resources(category_id);
CREATE INDEX reservations_resource_time_idx ON public.reservations(resource_id, start_time, end_time);
CREATE INDEX reservations_user_id_idx ON public.reservations(user_id);
CREATE INDEX reservations_team_id_idx ON public.reservations(team_id);

